export const formatKarteDataForPrompt = (kartes: {
  id: string;
  date: string;
  good: string;
  improve: string;
  homework: string;
}[]) => {
  if (kartes.length === 0) return '[]';
  return JSON.stringify(kartes, null, 2);
};
